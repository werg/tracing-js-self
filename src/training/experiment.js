// Reproducible, fail-closed actual-model comparison over a frozen common cohort.
// Historical v2 baseline is evaluated by its PINNED EXTERNAL harness, never
// parsed or replayed through the active v3 production parser.
import {createHash} from 'node:crypto';
import {isDeepStrictEqual} from 'node:util';
import {evaluateSelectedTrajectory} from './rollout.js';

export const EXPERIMENT_CONDITIONS=Object.freeze([
  'historical-v2','v3-fine','v3-fused','v3-expr-2','v3-expr-4',
  'v3-expr-8','v3-collections','v3-outcome-only'
]);
export const EXPERIMENT_SEEDS=Object.freeze([17,29,43]);
const hex=/^[0-9a-f]{64}$/;
const commit=/^[0-9a-f]{40}$/;
const allowedOutcomes=new Set(['correct','incorrect','invalid','incomplete']);
const fail=(message)=>{throw new Error('Semantic experiment refused: '+message);};
const digest=data=>createHash('sha256').update(JSON.stringify(data)).digest('hex');

export function experimentCaseId(exported) {
  if(exported?.public?.schema!=='semantic-execution/3' ||
     exported.public.traceFormat!=='semantic-trace/3'||
     !Array.isArray(exported.public.groups))fail('reference is not a v3 exported case');
  const observed=exported.public.groups.filter(g=>g.mode==='observed');
  if(!observed.length)fail('reference context absent');
  return digest({profile:exported.public.profile,
    contextFormat:exported.public.contextFormat,
    records:observed.map(g=>g.events?.map(e=>e.record))});
}
export function freezeExperimentCohort(references) {
  if(!Array.isArray(references)||!references.length)
    fail('cannot freeze an empty reference cohort');
  const ids=new Set(),families=new Set(),cases=[];
  for(const row of references){
    if(row?.sidecar?.referenceStatus!=='agreed'||row.sidecar.split!=='test'||
       typeof row.sidecar.sourceLineage!=='string'||!row.sidecar.sourceLineage)
      fail('reference lacks independently verified test family provenance');
    const caseId=experimentCaseId(row);
    if(ids.has(caseId))fail('duplicate frozen test source and input');
    ids.add(caseId);families.add(row.sidecar.sourceLineage);
    cases.push({caseId,family:row.sidecar.sourceLineage});
  }
  return {schema:'semantic-frozen-cohort/1',cohortSha256:digest([...ids].sort()),
    families:[...families].sort(),cases:cases.sort((a,b)=>a.caseId.localeCompare(b.caseId)),
    scope:'verified observed source and supplied input only'};
}

export function validateExperimentManifest(manifest) {
  if(!manifest||manifest.schema!=='semantic-learning-experiment/1')
    fail('manifest schema');
  const pinned=manifest.pinned??{},training=manifest.training??{};
  for(const key of ['tracerCommit','consumerCommit','historicalCommit'])
    if(!commit.test(pinned[key]??''))fail('missing exact Git commit '+key);
  for(const key of ['tokenizerSha256','initialCheckpointSha256','frozenCohortSha256'])
    if(!hex.test(pinned[key]??''))fail('missing content digest '+key);
  for(const key of ['architecture','optimizer','budgets','hardware']){
    if(!training[key]||typeof training[key]!=='object'||
       Array.isArray(training[key])||!Object.keys(training[key]).length)
      fail('missing '+key+' configuration');
  }
  if(!isDeepStrictEqual(manifest.seeds,EXPERIMENT_SEEDS))
    fail('seeds must be 17, 29, 43');
  if(!isDeepStrictEqual(manifest.conditions,EXPERIMENT_CONDITIONS))
    fail('prespecified historical baseline and all v3 comparisons required');
  for(const key of ['train','validation','test']){
    const split=manifest.splits?.[key];
    if(!split||!hex.test(split.sha256??'')||
       !Array.isArray(split.families)||!split.families.length)
      fail('missing frozen '+key+' family split and content digest');
  }
  const seen=new Set();
  for(const key of ['train','validation','test'])
    for(const family of manifest.splits[key].families){
      if(seen.has(family))fail('family split leakage: '+family);
      seen.add(family);
    }
  return true;
}
function outcomeForActualModel(candidate,reference) {
  if(candidate?.provenance?.source!=='free-running-model' ||
     typeof candidate.provenance.checkpointSha256!=='string'||
     !hex.test(candidate.provenance.checkpointSha256)||
     !Array.isArray(candidate.groups))
    fail('missing actual-model provenance, checkpoint or selected groups');
  // Observed source/input is supplied by the environment, not generated by
  // the model. Do not score a transcript that replaces the frozen observed
  // prefix with a conveniently easier source or modified input graph.
  const expected=reference.public.groups;
  const expectedStart=expected.findIndex(g=>g.mode==='generated');
  const actualStart=candidate.groups.findIndex(g=>g.mode==='generated');
  if(expectedStart<2||actualStart!==expectedStart ||
     !isDeepStrictEqual(candidate.groups.slice(0,actualStart),
       expected.slice(0,expectedStart)))
    fail('selected model changed its frozen observed source/input context');
  const scored=evaluateSelectedTrajectory({
    groups:candidate.groups,
    referenceOutcome:reference.sidecar.reference,
    referenceGroups:expected
  });
  const correctness=scored.invalid?.category==='incomplete'?'incomplete':
    scored.invalid?'invalid':
    scored.correctness==='correct'?'correct':'incorrect';
  return {correctness,witnessViolation:!!scored.firstWitnessViolation,
    firstWitnessViolation:scored.firstWitnessViolation,
    referenceTextDifference:!!scored.firstReferenceTraceDifference,
    observableMismatch:!!scored.observableMismatch};
}
function outcomeForHistorical(candidate) {
  if(candidate?.provenance?.source!=='pinned-historical-runner'||
     !commit.test(candidate.provenance.historicalCommit??'')||
     !hex.test(candidate.provenance.evaluationReceiptSha256??'')||
     !allowedOutcomes.has(candidate.externalAdjudication?.correctness))
    fail('historical baseline requires pinned independent evaluation receipt');
  return {correctness:candidate.externalAdjudication.correctness,
    witnessViolation:!!candidate.externalAdjudication.witnessViolation,
    firstWitnessViolation:null,referenceTextDifference:false,
    observableMismatch:candidate.externalAdjudication.correctness==='incorrect'};
}
function meters(candidate) {
  const values=candidate?.measurements;
  for(const key of ['generatedTokens','observedTokens','predictionGroups',
    'latencyMilliseconds','computeFlops','peakMemoryBytes']){
    if(typeof values?.[key]!=='number'||!Number.isFinite(values[key])||values[key]<0)
      fail('missing measured '+key);
  }
  return values;
}
function familyMean(rows) {
  const families=new Map();
  for(const row of rows){
    const list=families.get(row.family)??[];list.push(row.correctness==='correct'?1:0);
    families.set(row.family,list);
  }
  return new Map([...families].map(([family,v])=>[family,
    v.reduce((a,b)=>a+b,0)/v.length]));
}
function mean(values){return values.reduce((a,b)=>a+b,0)/values.length;}
function pairedIntervals(left,right) {
  const a=familyMean(left),b=familyMean(right);
  if(a.size!==b.size||[...a].some(([k])=>!b.has(k)))
    fail('baseline and condition have different held-out family cohort');
  const differences=[...a].map(([family,value])=>b.get(family)-value);
  const sampleSize=differences.length;
  let state=0x5eed17;
  const draws=[];
  for(let draw=0;draw<2000;draw++){
    const vals=[];
    for(let i=0;i<sampleSize;i++){
      state=(Math.imul(state,1664525)+1013904223)>>>0;
      vals.push(differences[state%sampleSize]);
    }
    draws.push(mean(vals));
  }
  draws.sort((x,y)=>x-y);
  return {unit:'held-out-source-family',difference:mean(differences),
    lower95:draws[49],upper95:draws[1949],familyCount:sampleSize,
    draws:2000};
}
export function evaluateActualModelExperiment({manifest,references,runs}) {
  validateExperimentManifest(manifest);
  if(!Array.isArray(references)||!references.length||!Array.isArray(runs))
    fail('actual held-out references and run artifacts required');
  const frozen=manifest.splits.test.families;
  const referenceById=new Map(),families=new Set();
  for(const ref of references){
    if(ref?.sidecar?.referenceStatus!=='agreed'||ref.sidecar.split!=='test')
      fail('test reference lacks independently verified and frozen split');
    if(!frozen.includes(ref.sidecar.sourceLineage))
      fail('reference family not in frozen test partition');
    const id=experimentCaseId(ref);
    if(referenceById.has(id))fail('duplicate cohort case identity');
    referenceById.set(id,ref);families.add(ref.sidecar.sourceLineage);
  }
  if(families.size!==frozen.length)fail('frozen source family has no test examples');
  if(digest([...referenceById.keys()].sort())!==manifest.pinned.frozenCohortSha256)
    fail('frozen cohort digest mismatch');
  const runIndex=new Map();
  for(const run of runs){
    if(!EXPERIMENT_CONDITIONS.includes(run.condition)||
       !EXPERIMENT_SEEDS.includes(run.seed)||!Array.isArray(run.cases)||
       run.cases.length!==references.length)fail('invalid or incomplete experiment run');
    const key=run.condition+':'+run.seed;
    if(runIndex.has(key))fail('duplicate condition/seed run');
    runIndex.set(key,run);
  }
  if(runIndex.size!==manifest.conditions.length*manifest.seeds.length)
    fail('not all required real model runs provided');
  const rows=[],summaries=[];
  for(const condition of manifest.conditions)for(const seed of manifest.seeds){
    const run=runIndex.get(condition+':'+seed);
    if(!run)fail('missing run '+condition+':'+seed);
    const seen=new Set(),items=[];
    for(const sample of run.cases){
      if(!referenceById.has(sample.caseId)||seen.has(sample.caseId))
        fail('unknown, repeated, or post-selected cohort case');
      seen.add(sample.caseId);
      const reference=referenceById.get(sample.caseId);
      const scored=condition==='historical-v2'?
        outcomeForHistorical(sample):outcomeForActualModel(sample,reference);
      if(condition==='historical-v2'&&
         sample.provenance.historicalCommit!==manifest.pinned.historicalCommit)
        fail('baseline evaluated under a different historical revision');
      const measured=meters(sample);
      items.push({condition,seed,caseId:sample.caseId,
        family:reference.sidecar.sourceLineage,
        ...scored,measurements:measured});
    }
    rows.push(...items);
    summaries.push({condition,seed,cases:items.length,
      correct:items.filter(x=>x.correctness==='correct').length,
      invalid:items.filter(x=>x.correctness==='invalid').length,
      witnessViolations:items.filter(x=>x.witnessViolation).length,
      modelTokens:items.reduce((a,x)=>a+x.measurements.generatedTokens,0),
      inferenceFlops:items.reduce((a,x)=>a+x.measurements.computeFlops,0)});
  }
  const baseline=rows.filter(r=>r.condition==='historical-v2');
  const pairs=manifest.conditions.filter(x=>x!=='historical-v2').map(condition=>({
    condition,comparedTo:'historical-v2',
    ...pairedIntervals(baseline,rows.filter(r=>r.condition===condition))
  }));
  return {schema:'semantic-learning-comparison/1',
    provenance:'real selected-model runs only; historical v2 baseline externally adjudicated',
    manifestSha256:digest(manifest),runs:summaries,pairedFamilyIntervals:pairs,
    metric:'free-running exact selected observable completion',
    measured:true};
}
